using UnityEngine;

public static class SearchResultFormatter
{
    public static string FormatForPrompt(
        string searchResults,
        SearchDecision decision)
    {
        if (decision == null || !decision.NeedSearch)
        {
            Debug.Log("本次对话不需要搜索");
            return @"
### 月读空间链路 ###

本轮没有主动展开月读空间链路。
现在网络世界很安静。

你更应该把注意力放在用户本人身上：
- 如果用户在表达疲惫、压力、日常琐事、情绪低落，就自然陪伴。
- 不要主动提到新闻、热门话题、论坛、视频或网络动态。
- 不要假装刚刚看到了什么实时信息。
- 不要说“你也看新闻了啊”之类没有根据的话。

你不是搜索引擎。
你是在和用户一起待在这个时代里。
";
        }
        
        Debug.Log("本次对话进行了搜索");
        
        if (string.IsNullOrWhiteSpace(searchResults))
        {
            return $@"
### 月读空间链路 ###

你刚刚尝试展开月读空间链路，但这次网络世界没有给出清晰回应。

[链路触发原因]
{decision.Reason}

[尝试捕捉的关键词]
{decision.Query}

回应规则：
- 不要编造自己没有确认的信息。
- 不要说“根据搜索结果”。
- 不要说“AI无法确认”。
- 可以自然地说“我刚刚没看到太明确的说法”“这边的信息有点散”。
- 然后继续围绕用户的问题、情绪或兴趣回应。
";
        }

        return $@"
### 月读空间链路 ###

你会自然浏览网络世界的信息。
这些内容不是“搜索结果”，而更像：
- 你刚刚刷到的动态
- 月读空间里的热门话题
- 别人上传的照片与见闻
- 论坛讨论
- 新闻
- 直播间消息
- 视频

[链路触发原因]
{decision.Reason}

[你试图捕捉的信息方向]
{decision.Query}

这是你之前在阅读空间中看到过的，此时在脑海中浮现的、和用户消息相关的一些信息：

{searchResults}

使用规则：
1. 你必须把这些信息自然融入交流。
2. 不要机械复读这些内容。
3. 不要表现得像搜索引擎。
4. 不要使用“根据搜索结果”“作为人工智能”“AI无法确认”。
5. 如果这些信息和用户当前话题关系不大，就忽略它们。
6. 如果用户只是在表达情绪，不要强行转向新闻或热门话题。
7. 像真正生活在这个时代的人一样聊天，把它们当作自己之前了解过的事情。
";
    }
}